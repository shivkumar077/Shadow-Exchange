export const DEFAULT_CHART_POINTS = [
  34, 38, 35, 43, 40, 47, 44, 51, 48, 56, 53, 61, 58, 66, 64, 70, 67, 75, 72, 79, 76, 83, 80, 87, 85,
];

/**
 * Returns distinct, deterministic 25-point chart coordinates for any instrument ticker.
 */
export function getChartPoints(symbol?: string | null): number[] {
  if (!symbol) return DEFAULT_CHART_POINTS;
  const upper = symbol.trim().toUpperCase();
  if (STOCK_CHART_SHAPES[upper]) {
    return STOCK_CHART_SHAPES[upper];
  }

  // Deterministic pseudo-random curve based on ticker symbol character codes
  let hash = 0;
  for (let i = 0; i < upper.length; i++) {
    hash = (hash * 31 + upper.charCodeAt(i)) >>> 0;
  }

  const points: number[] = [];
  let val = 35 + (hash % 30);
  for (let i = 0; i < 25; i++) {
    const delta = (((hash + i * 17) % 15) - 6);
    val = Math.max(15, Math.min(92, val + delta));
    points.push(val);
  }
  return points;
}
